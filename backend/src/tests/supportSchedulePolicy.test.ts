import assert from "node:assert/strict";
import { assertTimezone, clockMinutes, isAbsent, isWithinScheduledHours, normalizeShifts } from "../services/supportSchedulePolicy.js";
const hours = normalizeShifts([{ day: 1, start: "09:00", end: "17:00" }]);
const berlin = { timezone: "Europe/Berlin", weeklyShifts: hours };
assert.equal(isWithinScheduledHours(null, new Date("2026-10-26T03:00:00Z")), true, "legacy no-schedule allows default availability");
assert.equal(isWithinScheduledHours(berlin, new Date("2026-10-26T07:59:00Z")), false);
assert.equal(isWithinScheduledHours(berlin, new Date("2026-10-26T08:00:00Z")), true);
assert.equal(isWithinScheduledHours(berlin, new Date("2026-10-26T16:00:00Z")), false);
assert.equal(isWithinScheduledHours(berlin, new Date("2026-07-06T07:00:00Z")), true, "summer DST should be respected");
assert.equal(isWithinScheduledHours(berlin, new Date("2026-07-06T15:00:00Z")), false);
assert.equal(isWithinScheduledHours(berlin, new Date("2026-07-05T08:00:00Z")), false, "non-working day should be excluded");
const now = new Date("2026-10-26T08:00:00Z");
assert.equal(isAbsent([{ startsAt: now, endsAt: new Date(now.getTime()+3600000) }], now), true);
assert.equal(isAbsent([{ startsAt: new Date(now.getTime()-3600000), endsAt: now }], now), false, "absence end is exclusive");
assert.equal(isAbsent([], now), false);
assert.equal(clockMinutes("16:45"), 1005);
assert.throws(() => clockMinutes("25:00"));
assert.throws(() => normalizeShifts([{ day: 1, start: "17:00", end: "09:00" }]), /Invalid/);
assert.throws(() => normalizeShifts([{ day: 1, start: "09:00", end: "12:00" }, { day: 1, start: "11:59", end: "17:00" }]), /Overlapping/);
assert.throws(() => assertTimezone("Fake/Unknown"), /Invalid/);
assert.equal(assertTimezone("Europe/Berlin"), "Europe/Berlin");
console.log("Support schedule and absence policy tests passed");
